"""Build the release zip (also the payload embedded in the EXE installer).

BepInEx, XUnity.AutoTranslator and the .NET runtime are taken from a working
install in the game folder; translations, scripts, readme and licenses come
from this repo. Logs (they contain the player's Steam ID), interop and cache
are never packed: BepInEx regenerates them on the player's machine.

    python -X utf8 tools/build_package.py --game "E:/SteamLibrary/steamapps/common/CONVRGENCE"
"""
import argparse
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xua_text  # noqa: E402

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
VERSION = "1.3"

GAME_FILES = ["winhttp.dll", "doorstop_config.ini", ".doorstop_version"]
GAME_TREES = ["dotnet", "BepInEx/core", "BepInEx/plugins", "BepInEx/config", "BepInEx/unity-libs"]


def walk(base, arc_prefix):
    for dp, _, files in os.walk(base):
        for n in files:
            full = os.path.join(dp, n)
            yield full, (arc_prefix + "/" + os.path.relpath(full, base)).replace("\\", "/")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", required=True, help="CONVRGENCE folder with BepInEx + XUA installed")
    ap.add_argument("--out", default=os.path.join(REPO, "dist", "CONVRGENCE-zh-TW-v%s.zip" % VERSION))
    args = ap.parse_args()

    text_dir = os.path.join(REPO, "translation", "zh-TW", "Text")
    bad = [(f, l) for f, l, k, _ in xua_text.load(text_dir) if k is None]
    if bad:
        for f, l in bad:
            print("UNREADABLE", f, "|", l[:120])
        sys.exit("translation files contain lines XUA would drop")

    entries = [(os.path.join(args.game, f), f) for f in GAME_FILES]
    for t in GAME_TREES:
        entries += list(walk(os.path.join(args.game, t), t))
    translations = [(p, a) for p, a in walk(text_dir, "BepInEx/Translation/zh-TW/Text")
                    if not a.endswith("_AutoGeneratedTranslations.txt")]
    entries += [(p, a) for p, a in translations if not os.path.basename(p).startswith("convrgence")]
    displayed = [(p, a) for p, a in translations if os.path.basename(p).startswith("convrgence")]
    plugin_dll = os.path.join(REPO, "plugin", "bin", "Release", "net6.0", "ConvrgenceZhFix.dll")
    if not os.path.exists(plugin_dll):
        sys.exit("build the plugin first: dotnet build plugin -c Release")
    entries.append((plugin_dll, "BepInEx/plugins/ConvrgenceZhFix.dll"))
    pkg = os.path.join(REPO, "package")
    entries += [(os.path.join(pkg, f), f) for f in ("toggle-chinese.bat", "Toggle-Chinese.ps1")]
    entries += list(walk(os.path.join(pkg, "LICENSES"), "LICENSES"))
    # the plugin comes from this repo's build, and its config must start from defaults
    # (a tester's config may have debug options switched on)
    skip = {"BepInEx/plugins/ConvrgenceZhFix.dll", "BepInEx/config/zh-tw.convrgence.textfix.cfg"}
    entries = [(p, a) for p, a in entries
               if not a.endswith(".log") and (a not in skip or p == plugin_dll)]
    arcs = [a for _, a in entries]
    assert len(arcs) == len(set(arcs)), "duplicate paths in package"

    readme = open(os.path.join(pkg, "README-zh-TW.txt"), encoding="utf-8").read()
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with zipfile.ZipFile(args.out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for src, arc in entries:
            z.write(src, arc)
        # translations: swap characters the game's fonts lack (see xua_text.DISPLAY_SUBSTITUTIONS)
        for src, arc in displayed:
            raw = open(src, "rb").read()
            bom = "﻿" if raw.startswith(b"\xef\xbb\xbf") else ""
            z.writestr(arc, (bom + xua_text.display_file_text(raw.decode("utf-8-sig"))).encode("utf-8"))
        # BOM + CRLF so the readme opens correctly in any Notepad
        z.writestr("README-zh-TW.txt", "\ufeff" + readme.replace("\r\n", "\n").replace("\n", "\r\n"))
        z.writestr("BepInEx/patchers/", "")
    print("%d files -> %s (%d bytes)" % (len(entries) + len(displayed) + 1, args.out, os.path.getsize(args.out)))


if __name__ == "__main__":
    main()
